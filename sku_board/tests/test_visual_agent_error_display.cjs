const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../static/app.js'), 'utf8');
const context = {syncAiImageStateFromConversation(){},renderAiImageSidebar(){},renderAiImageForm(){},renderAiImageResults(){},AI_IMAGE_DIRECTOR_STAGES:[]};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function enforceAiImageCodSourceCoverage('), source.indexOf('async function prepareAiImageSuitePlan(')), context);
const conversation = {suiteKey:'cod-country-landing-30'};
const payload = {visualPipelineVersion:'cod-visual-agents-v1',companyPromptStatus:{ready:false},suitePages:[],director:{stage:'product',creativePassWarning:'upstream write timed out',sellingPointCoverage:{complete:false}}};
assert.throws(()=>context.enforceAiImageCodSourceCoverage(conversation,payload), /upstream write timed out/);
assert.equal(conversation.director.stage,'product');
assert.ok(!conversation.error.includes('0/0'));
assert.doesNotThrow(()=>context.enforceAiImageCodSourceCoverage(conversation,{director:{sellingPointCoverage:{checked:false,complete:false}}}));
assert.throws(()=>context.enforceAiImageCodSourceCoverage(conversation,{director:{sellingPointCoverage:{complete:false,total:10,assigned:8,missing:['test']}}}), /8\/10/);
const partial={...payload,director:{stage:'prompts'},continuation:{message:'6/24 页已保留'}};
assert.throws(()=>context.enforceAiImageCodSourceCoverage(conversation,partial),/策划进度已保存/);
assert.equal(conversation.director.stage,'prompts');
const diagnosticStart=source.indexOf('function aiImageErrorDiagnosis(');
vm.runInContext(source.slice(source.indexOf('function aiImageSavedPlanError('),source.indexOf('async function syncAiImageSavedPlan(')),context);
vm.runInContext(source.slice(diagnosticStart,source.indexOf('\nfunction ',diagnosticStart+1)),context);
const diagnosis=context.aiImageErrorDiagnosis('AI 策划尚未完成：DirectorBudgetExhausted: AI 导演响应超时：20 秒');
assert.ok(diagnosis.title.startsWith('AI 策划'));
assert.equal(JSON.stringify(diagnosis.actions),'["retry"]');
assert.ok(!diagnosis.reason.includes('临时降级'));
assert.equal(context.aiImageErrorDiagnosis('动态页面内容与已保存版本不同').title,'生图前方案校验未通过');
console.log('Actual Agent errors preserved; unchecked coverage skipped; legacy coverage enforced');
